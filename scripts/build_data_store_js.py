import json
from pathlib import Path

out_dir = Path(r"C:\Kiến thức cần học\CRM\output")
data_dir = out_dir / "data"
src_dir = out_dir / "src"

files = [
    ("curriculum", data_dir / "curriculum.json"),
    ("glossary", data_dir / "glossary.json"),
    ("flashcards", data_dir / "flashcards.json"),
    ("exams", data_dir / "exams.json"),
    ("questionBank", data_dir / "question-bank.json"),
    ("cases", data_dir / "cases.json"),
    ("manifest", data_dir / "source-manifest.json"),
    ("translations", src_dir / "i18n" / "translations.json")
]

bundle = {}
for name, p in files:
    if p.exists():
        bundle[name] = json.loads(p.read_text(encoding="utf-8"))
    else:
        print(f"Warning: {p} does not exist!")

js_content = f"// Autogenerated Data Store for standalone browser execution\nwindow.CRM_DATA = {json.dumps(bundle, indent=2, ensure_ascii=False)};\n"
store_path = src_dir / "data-store.js"
store_path.write_text(js_content, encoding="utf-8")
print(f"Generated data-store.js ({store_path.stat().st_size} bytes)")
